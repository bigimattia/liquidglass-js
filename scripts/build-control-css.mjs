import { readFile, writeFile } from "node:fs/promises";
import { compile } from "tailwindcss";

const source = await readFile(new URL("../demo/native-controls.js", import.meta.url), "utf8");
const theme = await readFile(new URL(import.meta.resolve("tailwindcss/theme.css")), "utf8");
const compiler = await compile(theme + "\n@tailwind utilities;");
// Include utility tokens from the preview templates and shared class strings.
const candidates = source.match(/[^\s"'\x60<>$]+/g) ?? [];
const output = new URL("../demo/control-utilities.css", import.meta.url);
await writeFile(output, "/* Generated by mise run demo-css. */\n" + compiler.build(candidates));
